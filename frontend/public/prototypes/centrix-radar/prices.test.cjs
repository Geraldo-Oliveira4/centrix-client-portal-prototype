const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const context=vm.createContext({mode:'parcial',followed:['r1'],window:{matchMedia:()=>({addEventListener(){}})}});
vm.runInContext(readFileSync(__dirname+'/prices.js','utf8'),context);
const run=code=>vm.runInContext(code,context);
assert.equal(run('currentPrice(priceRoutes[0])'),2250);
assert.ok(Math.abs(run('pct(2250,2450)')-(-8.163265306122447))<1e-9);
assert.equal(run('pct(null,2450)'),null);
assert.equal(run('pct(2450,0)'),null);
assert.equal(run('currentPrice(priceRoutes[1])'),null);
context.mode='sem-fontes';
assert.equal(run('currentPrice(priceRoutes[0])'),null);
context.mode='parcial';
assert.equal(run('priceRoutes[0].own.filter(x=>x.comparable).length'),2);
assert.equal(run('Math.min(...priceRoutes[0].windows.slice(-4).flatMap(observations))'),2100);
assert.equal(run('Math.max(...priceRoutes[0].windows.slice(-4).flatMap(observations))'),2670);
assert.equal(run('Math.max(...priceRoutes[0].windows.flatMap(observations))'),2950);
assert.equal(run('priceRoutes[0].windows.every(w=>{const a=observations(w);return a.length===6&&(a[2]+a[3])/2===w.median})'),true);
assert.equal(run("ensurePriceRoute({origin:'CNSHA',destination:'BRSSZ',equipment:'40HC',service:'1 conexão'}).id"),'r1');
assert.equal(run('priceRoutes.length'),2);
assert.equal(run("ensurePriceRoute({origin:'CNNGB',destination:'BRPNG',equipment:'20GP',service:'Direto'}).preferred"),false);
assert.equal(run('priceRoutes.at(-1).windows.length+priceRoutes.at(-1).own.length'),0);
assert.equal(run('currentPrice(priceRoutes.at(-1))'),null);
assert.equal(run("ensurePriceRoute({origin:'invalid',destination:'BRPNG',equipment:'20GP',service:'Direto'})"),null);
console.log('17 verificações de cálculo, cobertura e adição de rota passaram.');
